def run_timeline_benchmark(
    max_samples: int | None = None,
    skip_tier1: bool = False,
    skip_tier2: bool = False,
) -> dict[str, Any]:
    """Run the full timeline benchmark (both tiers).

    Returns:
        Dict with ``tier1`` (list of TimelineScore dicts) and
        ``tier2`` (LexTime results dict or None).
    """
    results: dict[str, Any] = {"tier1": None, "tier2": None}

    if not skip_tier1:
        scores = run_tier1_benchmark(max_docs=max_samples)
        results["tier1"] = [
            {
                "doc": s.doc_name,
                "event_recall": s.event_recall,
                "order_accuracy": s.order_accuracy,
                "date_parse_rate": s.date_parse_rate,
                "found": s.events_found,
                "expected": s.total_expected,
            }
            for s in scores
        ]

    if not skip_tier2:
        results["tier2"] = run_lextime_benchmark(max_samples=max_samples)

    return results
