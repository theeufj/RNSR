@dataclass
class TimelineScore:
    """Scores for a single timeline extraction run."""
    doc_name: str
    total_expected: int
    events_found: int
    event_recall: float
    order_accuracy: float
    date_parse_rate: float
    details: list[dict[str, Any]] = field(default_factory=list)


def _keyword_match_count(extracted_desc: str, expected: ExpectedEvent) -> int:
    """Count how many of the expected keywords appear in the extracted text."""
    desc_lower = extracted_desc.lower()
    return sum(1 for kw in expected.keywords if kw.lower() in desc_lower)


def _event_matches(extracted_desc: str, expected: ExpectedEvent, min_keywords: int = 2) -> bool:
    """Check if an extracted event description matches an expected event.

    Requires at least ``min_keywords`` keywords to appear in the description.
    This prevents false matches from generic words like "construction" or
    "appeal" that appear in multiple events.
    """
    return _keyword_match_count(extracted_desc, expected) >= min_keywords


def _date_matches(parsed: datetime | None, expected: ExpectedEvent) -> bool:
    """Check if a parsed date matches the expected date."""
    if parsed is None:
        return False
    return (
        parsed.year == expected.year
        and parsed.month == expected.month
        and parsed.day == expected.day
    )


def _build_combined_text(evt: Any) -> str:
    """Build a searchable text string from an extracted event."""
    desc = getattr(evt, "description", "") or ""
    entities = " ".join(getattr(evt, "entities_involved", []) or [])
    return f"{desc} {entities}"


def evaluate_timeline(
    extracted_events: list[Any],  # list of TimelineEvent
    expected_events: list[ExpectedEvent],
) -> TimelineScore:
    """Score extracted timeline events against ground truth.

    Uses date-aware best-match selection with one-to-one assignment:
    1. For each expected event, collect ALL candidate matches (2+ keywords).
    2. Prefer the candidate whose parsed date matches exactly.
    3. Fall back to the candidate with the most keyword matches.
    4. Once an extracted event is matched, it cannot be reused.

    Args:
        extracted_events: Output from ``extract_timeline()``.
        expected_events: Known ground-truth events.

    Returns:
        TimelineScore with recall, ordering, and date-parse metrics.
    """
    matched: list[tuple[int, Any]] = []  # (expected_idx, extracted_event)
    unmatched_expected: list[int] = []
    details: list[dict[str, Any]] = []
    used_extracted: set[int] = set()  # indices of extracted events already matched

    for i, exp in enumerate(expected_events):
        # Collect all candidate matches (with 2+ keywords, not already used)
        candidates: list[tuple[int, int, bool]] = []  # (ext_idx, kw_count, date_ok)
        for j, evt in enumerate(extracted_events):
            if j in used_extracted:
                continue
            combined = _build_combined_text(evt)
            kw_count = _keyword_match_count(combined, exp)
            if kw_count >= 2:
                date_ok = _date_matches(getattr(evt, "date_parsed", None), exp)
                candidates.append((j, kw_count, date_ok))

        if candidates:
            # Sort: prefer date match first, then highest keyword count
            candidates.sort(key=lambda c: (c[2], c[1]), reverse=True)
            best_idx, best_kw, best_date = candidates[0]
            best_evt = extracted_events[best_idx]
            used_extracted.add(best_idx)

            matched.append((i, best_evt))
            details.append({
                "expected": exp.date_str,
                "found": True,
                "date_correct": best_date,
                "kw_matched": best_kw,
            })
        else:
            unmatched_expected.append(i)
            details.append({
                "expected": exp.date_str,
                "found": False,
                "keywords": exp.keywords,
            })

    # Event recall
    event_recall = len(matched) / len(expected_events) if expected_events else 0.0

    # Date parse rate (among matched events)
    dates_parsed = sum(
        1 for _, evt in matched
        if getattr(evt, "date_parsed", None) is not None
    )
    date_parse_rate = dates_parsed / len(matched) if matched else 0.0

    # Order accuracy: check that matched events appear in chronological order
    # by comparing their positions in the extracted list
    if len(matched) >= 2:
        extracted_positions = []
        for _, evt in matched:
            try:
                pos = extracted_events.index(evt)
            except ValueError:
                pos = -1
            extracted_positions.append(pos)

        correct_pairs = 0
        total_pairs = 0
        for a in range(len(extracted_positions)):
            for b in range(a + 1, len(extracted_positions)):
                total_pairs += 1
                if extracted_positions[a] < extracted_positions[b]:
                    correct_pairs += 1
        order_accuracy = correct_pairs / total_pairs if total_pairs else 1.0
    else:
        order_accuracy = 1.0

    return TimelineScore(
        doc_name="",
        total_expected=len(expected_events),
        events_found=len(matched),
        event_recall=event_recall,
        order_accuracy=order_accuracy,
        date_parse_rate=date_parse_rate,
        details=details,
    )


def run_tier1_benchmark(
    max_docs: int | None = None,
) -> list[TimelineScore]:
    """Run the Tier 1 synthetic-PDF timeline benchmark.

    Ingests the test PDFs, extracts timelines, and scores against ground truth.

    Returns:
        List of TimelineScore (one per document).
    """
    from rnsr import ingest_document, build_skeleton_index
    from rnsr.indexing.knowledge_graph import InMemoryKnowledgeGraph
    from rnsr.extraction.rlm_unified_extractor import extract_entities_and_relationships
    from rnsr.extraction.timeline_extractor import extract_timeline

    test_cases: list[tuple[str, list[ExpectedEvent]]] = [
        ("Timeline - Meridian Project History.pdf", MERIDIAN_EVENTS),
        ("Timeline - Baxter v Thornton.pdf", BAXTER_EVENTS),
    ]

    if max_docs:
        test_cases = test_cases[:max_docs]

    scores: list[TimelineScore] = []

    for pdf_name, expected in test_cases:
        pdf_path = TEST_DOCS_DIR / pdf_name
        if not pdf_path.exists():
            logger.warning("timeline_bench_pdf_missing", path=str(pdf_path))
            continue

        logger.info("timeline_bench_processing", doc=pdf_name)

        # Ingest
        result = ingest_document(str(pdf_path))
        skeleton, kv_store = build_skeleton_index(result.tree)

        # Build KG
        kg = InMemoryKnowledgeGraph()
        for node_id, node in skeleton.items():
            content = kv_store.get(node_id) or ""
            if len(content.strip()) < 20:
                continue
            try:
                ext_result = extract_entities_and_relationships(
                    node_id=node_id,
                    doc_id=pdf_name,
                    header=node.header,
                    content=content,
                )
                for entity in ext_result.entities:
                    kg.add_entity(entity)
                for rel in ext_result.relationships:
                    kg.add_relationship(rel)
            except Exception as exc:
                logger.debug("extraction_error", node=node_id, error=str(exc))

        # Extract timeline (KG + direct text scan for higher recall)
        events = extract_timeline(kg, skeleton=skeleton, kv_store=kv_store)

        # Score
        score = evaluate_timeline(events, expected)
        score.doc_name = pdf_name
        scores.append(score)

        logger.info(
            "timeline_bench_result",
            doc=pdf_name,
            recall=f"{score.event_recall:.0%}",
            order=f"{score.order_accuracy:.0%}",
            date_parse=f"{score.date_parse_rate:.0%}",
            found=f"{score.events_found}/{score.total_expected}",
        )

    return scores


