# Loader (for integration with run_all_benchmarks.py)
# ============================================================================


class TimelineBenchLoader:
    """Loader for the timeline / temporal ordering benchmark.

    Returns a ``BenchmarkDataset`` of LexTime instances (Tier 2).
    Tier 1 (synthetic PDF) evaluation is run via ``run_tier1_benchmark()``.
    """

    @staticmethod
    def load(
        split: str = "test",
        max_samples: Optional[int] = None,
    ) -> BenchmarkDataset:
        """Load LexTime as a BenchmarkDataset.

        Each instance becomes a BenchmarkQuestion where:
        - question = temporal relation (TR)
        - answer = gold label (entailment / contradiction)
        - context = [paragraph]
        """
        rows = _load_lextime_csv()
        questions: list[BenchmarkQuestion] = []

        if rows is None:
            logger.warning("lextime_not_available_returning_empty_dataset")
            return BenchmarkDataset(
                name="timeline",
                description="LexTime: Temporal ordering of legal events (dataset not found)",
                questions=[],
                metrics=["accuracy"],
                source_url="https://zenodo.org/records/17157439",
            )

        for i, row in enumerate(rows):
            if max_samples and i >= max_samples:
                break
            label = row.get("label", "").strip().lower()
            if label not in ("entailment", "contradiction"):
                continue
            questions.append(
                BenchmarkQuestion(
                    id=f"lextime_{i:04d}",
                    question=row.get("TR", ""),
                    answer=label,
                    context=[row.get("paragraph", "")],
                    reasoning_type="temporal",
                    metadata={
                        "pair_type": row.get("pair_type", ""),
                        "source": "LexTime",
                    },
                )
            )

        return BenchmarkDataset(
            name="timeline",
            description=(
                "LexTime: Temporal ordering of legal events. "
                "514 instances from U.S. Federal Complaints. "
                "Task: classify temporal relation as entailment or contradiction."
            ),
            questions=questions,
            metrics=["accuracy"],
            source_url="https://zenodo.org/records/17157439",
        )


