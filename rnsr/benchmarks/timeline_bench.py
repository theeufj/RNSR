def _load_lextime_csv() -> list[dict[str, str]] | None:
    """Load the LexTime CSV if it exists."""
    csv_path = DATA_DIR / "Entailment_Dataset.csv"
    if not csv_path.exists():
        logger.info("lextime_csv_not_found", path=str(csv_path))
        return None
    with open(csv_path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def run_lextime_benchmark(
    llm_fn: Any | None = None,
    max_samples: int | None = None,
) -> dict[str, Any] | None:
    """Run the LexTime temporal-ordering benchmark.

    Each instance has a paragraph, a temporal relation (TR) description,
    and a label (entailment or contradiction).  We ask the LLM to classify
    whether the TR is entailed or contradicted by the paragraph.

    Args:
        llm_fn: A ``Callable[[str], str]`` for classification. If None,
            attempts to create one via ``get_llm()``.
        max_samples: Limit the number of instances evaluated.

    Returns:
        Dict with accuracy, precision, recall, f1, and per-label breakdowns.
        Returns None if the dataset is not available.
    """
    rows = _load_lextime_csv()
    if rows is None:
        return None

    if max_samples:
        rows = rows[:max_samples]

    # Get or create LLM
    if llm_fn is None:
        try:
            from rnsr.llm import get_llm
            _llm = get_llm()
            llm_fn = lambda prompt: str(_llm.complete(prompt))
        except Exception as exc:
            logger.error("lextime_llm_init_failed", error=str(exc))
            return None

    correct = 0
    total = 0
    tp = {"entailment": 0, "contradiction": 0}
    fp = {"entailment": 0, "contradiction": 0}
    fn = {"entailment": 0, "contradiction": 0}

    for row in rows:
        paragraph = row.get("paragraph", "")
        tr = row.get("TR", "")
        gold_label = row.get("label", "").strip().lower()

        if gold_label not in ("entailment", "contradiction"):
            continue

        prompt = (
            "You are a temporal reasoning expert analysing legal documents.\n\n"
            "Given the following paragraph from a legal complaint, determine "
            "whether the temporal relation statement is ENTAILED or CONTRADICTED "
            "by the paragraph.\n\n"
            f"PARAGRAPH:\n{paragraph}\n\n"
            f"TEMPORAL RELATION:\n{tr}\n\n"
            "Answer with EXACTLY one word: entailment or contradiction"
        )

        try:
            raw = llm_fn(prompt).strip().lower()
            # Extract the classification
            if "contradiction" in raw:
                predicted = "contradiction"
            elif "entailment" in raw:
                predicted = "entailment"
            else:
                predicted = "unknown"
        except Exception:
            predicted = "unknown"

        total += 1
        if predicted == gold_label:
            correct += 1
            tp[gold_label] += 1
        else:
            if predicted in fp:
                fp[predicted] += 1
            fn[gold_label] += 1

    accuracy = correct / total if total else 0.0

    results: dict[str, Any] = {
        "total": total,
        "correct": correct,
        "accuracy": accuracy,
        "per_label": {},
    }

    for label in ("entailment", "contradiction"):
        precision = tp[label] / (tp[label] + fp[label]) if (tp[label] + fp[label]) else 0.0
        recall = tp[label] / (tp[label] + fn[label]) if (tp[label] + fn[label]) else 0.0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
        results["per_label"][label] = {
            "precision": precision,
            "recall": recall,
            "f1": f1,
        }

    logger.info(
        "lextime_benchmark_result",
        accuracy=f"{accuracy:.1%}",
        total=total,
        correct=correct,
    )

    return results


