"""
Timeline / Temporal Ordering Benchmark for RNSR

Two-tier benchmark:

Tier 1 -- Synthetic Ground Truth (self-contained, zero external deps)
    Uses the test PDFs generated by ``scripts/generate_test_pdfs.py`` with
    hardcoded expected events.  Validates the full pipeline: ingestion ->
    skeleton -> KG -> extract_timeline.

Tier 2 -- LexTime (external academic dataset)
    514 instances from U.S. Federal Complaints with annotated temporal
    relation descriptions and entailment/contradiction labels.
    Dataset: https://zenodo.org/records/17157439  (CC-BY-4.0)
    Paper:  "LexTime: A Benchmark for Temporal Ordering of Legal Events"
            (EMNLP 2025 Findings)

Metrics:
    - event_recall:  fraction of expected events that were extracted
    - order_accuracy: fraction of consecutive event pairs in correct order
    - date_parse_rate: fraction of events with a successfully parsed date
    - lextime_accuracy: classification accuracy on LexTime (Tier 2 only)

Usage:
    from rnsr.benchmarks.timeline_bench import TimelineBenchLoader
    dataset = TimelineBenchLoader.load(max_samples=10)

    # Or run the full evaluation directly:
    from rnsr.benchmarks.timeline_bench import run_timeline_benchmark
    results = run_timeline_benchmark()
"""

